   ORG  00H 
   RS  EQU P0.0 
   RW  EQU P0.1 
   E  EQU P0.2
   KP_PORT EQU P3 
   
  MAIN: MOV  SP, #70H 
        MOV  PSW, #00H
        MOV R0,#30H ; POINTER FOR STORING NUMBERS,SYMBOLS AND BRACKETS
        MOV R2,#00H; COUNTER FOR HOW MANY MEMORY LOCATIONS WE ARE USING 
   
LCD_IN:  MOV  A, #38H   ;init. LCD 2 lines, 5x7 matrix 
   ACALL COMNWRT   ;call command subroutine 
   ACALL  DELAY   ;give LCD some time 
   MOV   A, #0FH   ;dispplay on, cursor on 
   ACALL COMNWRT   ;call command subroutine 
   ACALL  DELAY   ;give LCD some time 
   MOV  A, #01    ;clear LCD 
   ACALL COMNWRT   ;call command subroutine 
   ACALL  DELAY   ;give LCD some time 
   MOV  A, #06H   ;shift cursor right 
   ACALL COMNWRT   ;call command subroutine 
   ACALL  DELAY   ;give LCD some time 
   MOV  A, #80H   ;cursor at line 1 postion 4 
   ACALL COMNWRT   ;call command subroutine 
   ACALL  DELAY   ;give LCD some time
   LJMP KEYBOARD_STARTS
   
  POW_PUSH_INTER:lJMP POW_PUSH ;PLACING THE INTERMEDIATE LOCATION HERE SO THAT NOT ALL GETS EXECUTED AND ALSO WITHINN RANGE
  PRIME_PUSH_INTER: LJMP PRIME_PUSH
  GCD_PUSH_INTER: LJMP GCD_PUSH
  EQUAL_PUSH_INTER:LJMP EQUAL_PUSH
  RESET_PUSH_INTER:LJMP RESET_PUSH
   
   
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;Keyboard starts;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;; 
KEYBOARD_STARTS:MOV KP_PORT,#0FH
K1:CLR KP_PORT.7
   CLR KP_PORT.6
   CLR KP_PORT.5
   CLR KP_PORT.4
   MOV A,KP_PORT
   ANL A,#00001111B
   CJNE A,#00001111B,K1
   
;CONFIGURING PUSH BUTTONS     
K2:JNB P2.3,POW_PUSH_INTER; IF POWER PUSH BUTTON IS PRESSED
   JNB P2.4,PRIME_PUSH_INTER; IF CHECK PRIME PUSH BUTTON IS PRESSED. JUMPING TO INTERMEDIATE LOCATION AS ADDRESS WAS GOING OUT OF RANGE
   JNB P2.5,GCD_PUSH_INTER; IF GCD/LCM PUSH BUTTON IS PRESSED
   JNB P2.6,EQUAL_PUSH_INTER; IF EQUALS PUSH BUTTON IS PRESSED
   JNB P2.7,RESET_PUSH_INTER; IF RESET PUSH BUTTON IS PRESSED
   
   LCALL DELAY
   MOV A,KP_PORT
   ANL A,#00001111B
   CJNE A,#00001111B,OVER
   SJMP K2
   
OVER:LCALL DELAY
     MOV A,KP_PORT
   ANL A,#00001111B
   CJNE A,#00001111B,OVER1
   SJMP K2 
   
OVER1:CLR KP_PORT.7
      SETB KP_PORT.6
      SETB KP_PORT.5
      SETB KP_PORT.4
      MOV A,KP_PORT
      ANL A,#00001111B
      CJNE A,#00001111B,ROW_0

      CLR KP_PORT.6
      SETB KP_PORT.7
      SETB KP_PORT.5
      SETB KP_PORT.4
      MOV A,KP_PORT
      ANL A,#00001111B
      CJNE A,#00001111B,ROW_1
      
      CLR KP_PORT.5
      SETB KP_PORT.7
      SETB KP_PORT.6
      SETB KP_PORT.4
      MOV A,KP_PORT
      ANL A,#00001111B
      CJNE A,#00001111B,ROW_2
      
      CLR KP_PORT.4
      SETB KP_PORT.7
      SETB KP_PORT.6
      SETB KP_PORT.5
      MOV A,KP_PORT
      ANL A,#00001111B
      CJNE A,#00001111B,ROW_3
      
ROW_0:MOV DPTR,#KCODE0
      SJMP FIND
ROW_1:MOV DPTR,#KCODE1
      SJMP FIND
ROW_2:MOV DPTR,#KCODE2
      SJMP FIND
ROW_3:MOV DPTR,#KCODE3
      SJMP FIND
FIND: RRC A
      JNC MATCH
      INC DPTR 
      SJMP FIND
      
MATCH:  CLR PSW.3 ;MAKING SURE REGISTER BANK 0 KEEPS SELECTED
        CLR PSW.4
        CLR A 
        MOVC A,@A+DPTR
        LCALL DATAWRT
        ;HERE WE HAVE TO FORM NUMBER UNTIL NO SYMBOLS HAVE BEEN PRESSED
        CLR A
        MOVC A,@A+DPTR ;AGAIN BRINGING THE NUMBER TO A IF GETS MODIFIED
        
        ;INITIALLY CHECKING IF THERE IS ANY BRACKETS. THEY WILL BE SENT DIRECTLY TO THE MEMORY
        CJNE A,#'(',CHECK_1  ;COMPARE EACH AND EVERY SYMBOL AND JUMPS TO NEXT KEY PRESS IF NOT EQUALS TO ANY NUMBER
        MOV @R0,A ; NUMBER IS NOT FORMED YET AS WE ARE STARTING 1ST BRACKET
        INC R0
        INC R2;KEEPING COUNT OF HOW MANY ITEMS ARE GOING INTO RAM LOCATIONS
        LJMP NEXT_KEY_PRESS
CHECK_1:CJNE A,#')',CHECK_2
	INC R0 ; GOING TO NEXT MEMORY AS NUMBER IS FORMED
	INC R2
	MOV R4,#00H; CLEARING THE OLD FORMING NUMBER
	MOV @R0,A ; ADING THE SYMBOL IN NEXT MEMOTY LOCATION
	INC R0
	INC R2;WE ARE NOT INCREMENTING IT AS WE ARE ASSUMING USER WILL PRESS A SYMBOL OR EQUAL RIGHT AFTER ')' WHICH WILL END NUMBER FORMATION AND R2 WILL GET INCREMENTED BY EITHER OPERATORS OR EQUAL SIGN
	LJMP NEXT_KEY_PRESS
	
CHECK_2:CJNE A,#'+',CHECK_3 ;ASSUMING NO WEIRD PEOPLE WILL PRESS A SYMBOL BEFORE ANY NUMBER
	MOV A,R0; WE WILL CHECK THE ELEMENT BEFORE +. WHAT WAS IN THAT MEMORY. NUMBER? OR ')'
	DEC A
	MOV R1,A
	MOV A,@R1;BRINGING THE PREVIOSU MEMORY CONTENT IN A
	CJNE A,#')',NUM_BEFORE_PLUS
	MOV @R0,#'+'
	INC R0
	INC R2
	LJMP NEXT_KEY_PRESS 
NUM_BEFORE_PLUS:INC R0 ; GOING TO NEXT MEMORY AS NUMBER IS FORMED
		INC R2
		MOV R4,#00H; CLEARING THE OLD FORMING NUMBER
		MOV @R0,#'+' ; ADING THE SYMBOL IN NEXT MEMOTY LOCATION
		INC R0
		INC R2;KEEPING COUNT OF HOW MANY ITEMS ARE GOING INTO RAM LOCATIONS
		LJMP NEXT_KEY_PRESS
CHECK_3:CJNE A,#'-',CHECK_4
	MOV A,R0; WE WILL CHECK THE ELEMENT BEFORE -. WHAT WAS IN THAT MEMORY. NUMBER? OR ')'
	DEC A
	MOV R1,A
	MOV A,@R1;BRINGING THE PREVIOSU MEMORY CONTENT IN A
	CJNE A,#')',NUM_BEFORE_MINUS
	MOV @R0,#'-' ;AS THERRE WAS A ) BEFORE -. WE CAN JUST SEND THE '-' IN RAM
	INC R0
	INC R2
	LJMP NEXT_KEY_PRESS 
NUM_BEFORE_MINUS:INC R0 ; GOING TO NEXT MEMORY
		 INC R2;KEEPING COUNT OF HOW MANY ITEMS ARE GOING INTO RAM LOCATIONS
		 MOV R4,#00H; CLEARING THE OLD FORMING NUMBER
		 MOV @R0,#'-' ; ADING THE SYMBOL IN NEXT MEMOTY LOCATION
		 INC R0
		 INC R2;KEEPING COUNT OF HOW MANY ITEMS ARE GOING INTO RAM LOCATIONS
		 LJMP NEXT_KEY_PRESS
CHECK_4:CJNE A,#'*',CHECK_5
	MOV A,R0; WE WILL CHECK THE ELEMENT BEFORE *. WHAT WAS IN THAT MEMORY. NUMBER? OR ')'
	DEC A
	MOV R1,A
	MOV A,@R1;BRINGING THE PREVIOSU MEMORY CONTENT IN A
	CJNE A,#')',NUM_BEFORE_MUL
	MOV @R0,#'*' ;AS THERE WAS A ) BEFORE *. WE CAN JUST SEND THE '*' IN RAM
	INC R0
	INC R2
	LJMP NEXT_KEY_PRESS	

NUM_BEFORE_MUL:INC R0 ; GOING TO NEXT MEMORY
	       INC R2;KEEPING COUNT OF HOW MANY ITEMS ARE GOING INTO RAM LOCATIONS
	       MOV R4,#00H; CLEARING THE OLD FORMING NUMBER
	       MOV @R0,#'*' ; ADING THE SYMBOL IN NEXT MEMOTY LOCATION
	       INC R0
	       INC R2;KEEPING COUNT OF HOW MANY ITEMS ARE GOING INTO RAM LOCATIONS
	       LJMP NEXT_KEY_PRESS
CHECK_5:CJNE A,#'/',FORM_NUMBER; IF NO SYMBOLS MATCHED THEN IT WAS A NUMBER
	MOV A,R0; WE WILL CHECK THE ELEMENT BEFORE /. WHAT WAS IN THAT MEMORY. NUMBER? OR ')'
	DEC A
	MOV R1,A
	MOV A,@R1;BRINGING THE PREVIOSU MEMORY CONTENT IN A
	CJNE A,#')',NUM_BEFORE_DIV
	MOV @R0,#'/' ;AS THERE WAS A ) BEFORE /. WE CAN JUST SEND THE '/' IN RAM
	INC R0
	INC R2
	LJMP NEXT_KEY_PRESS

NUM_BEFORE_DIV:INC R0 ; GOING TO NEXT MEMORY
	       INC R2;KEEPING COUNT OF HOW MANY ITEMS ARE GOING INTO RAM LOCATIONS
	       MOV R4,#00H; CLEARING THE OLD FORMING NUMBER
	       MOV @R0,#'/' ; ADING THE SYMBOL IN NEXT MEMOTY LOCATION
	       INC R0
	       INC R2;KEEPING COUNT OF HOW MANY ITEMS ARE GOING INTO RAM LOCATIONS
	       LJMP NEXT_KEY_PRESS      
      
FORM_NUMBER:CLR PSW.3; WE WILL USE THE R3,R4,R5 OF BANK 0 TO TEMPORARY STORE THE DIGITS TO FORM NUMBER
	    CLR PSW.4
	    CLR C
	    SUBB A,#30H ; CONVERTING TO HEX FROM ASCII
	    MOV R3,A; R3 IS STROING THE NEW DIGIT
	    
	    MOV A,R4; BRINGING OLD VALUE IN ACCUMULATOR
	    MOV B,#10; PREPARING FOR MUL
	    MUL AB ; OUR RESULT WILL BE IN A AS LOWER BYTE AS WE ARE NOT ALLOWING NUMBERS GREATER THAN 255
	    ADD A,R3; ADDING THE NEW DIGIT TO FORM THE CURRENT NUMBER
	    MOV R4,A; R4 WILL KEEP THE OLD NUMBER FOR NEXT ITERATION
	    MOV @R0,A; STROING THE NUMBER ALSO DIRECTLY IN CURRENT MEMORY
 
NEXT_KEY_PRESS:LCALL DELAY
    	       LJMP K1                     
 ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;KEYPAD ENDS;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
 
 ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;PUSH BUTTON STARTS;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
 POW_PUSH:LCALL DELAY;PREVENTING DEBOUNCING
          LCALL DELAY
          LCALL DELAY
          LCALL DELAY
          LCALL DELAY
          MOV A,#'^'
          LCALL DATAWRT
          LCALL DELAY
          MOV A,R0
          DEC A
          MOV R1,A
          MOV A,@R1
          CJNE A,#')',NUM_BEFORE_POW
          MOV @R0,#'^' ;AS THERE WAS A ) BEFORE ^. WE CAN JUST SEND THE '^' IN RAM
	  INC R0
	  INC R2
	  LJMP K1
	  
NUM_BEFORE_POW:INC R0 ; GOING TO NEXT MEMORY AS NUMBER IS FORMED
	       INC R2;KEEPING COUNT OF HOW MANY ITEMS ARE GOING INTO RAM LOCATIONS
               MOV R4,#00H; CLEARING THE OLD FORMING NUMBER
               MOV @R0,#'^'; ALSO STORING THESE EXTRA SYMBOLS IN RAM LOCATIONS
               INC R0
               INC R2
               LJMP K1
           
PRIME_PUSH:MOV DPTR,#PRIME_PROMPT1
PRIME_MSG1:CLR A
	   MOVC A,@A+DPTR
	   JZ FINISH_PRIME1
	   LCALL DATAWRT
	   LCALL DELAY
	   INC DPTR
	   LJMP PRIME_MSG1

FINISH_PRIME1:MOV A,#0C0H
	      LCALL COMNWRT
	      LCALL DELAY
	      
           MOV DPTR,#PRIME_PROMPT2
PRIME_MSG2:CLR A
	   MOVC A,@A+DPTR
	   JZ FINISH_PRIME2
	   LCALL DATAWRT
	   LCALL DELAY
	   INC DPTR
	   LJMP PRIME_MSG2
FINISH_PRIME2:MOV A,#'P' ; STROING P IN THE MEMORY TO INDICATE WE HAVE TO CHECK IF PRIME OR NOT FOR NUMBERS AFTERWARDS
	      MOV @R0,A; ALSO STORING THESE EXTRA SYMBOLS IN RAM LOCATIONS
              INC R0
              INC R2
	      LJMP K1

EQUAL_PUSH:LCALL DELAY;PREVENTING DEBOUNCING
          LCALL DELAY
          LCALL DELAY
          LCALL DELAY
          LCALL DELAY
          LCALL DELAY
          MOV A,R0
          DEC A
          MOV R1,A
          MOV A,@R1
          CJNE A,#')',FINAL_NUM_FORMING
          LJMP START_CALCULATING
          
FINAL_NUM_FORMING:INC R2; NUMBER ALREADY FORMED. SO ADDING +1 TO THE COUNTER
        	  MOV A,#'='
        	  LCALL DATAWRT
       	          LCALL DELAY
         	  LJMP START_CALCULATING

GCD_PUSH:MOV DPTR,#GCD_PROMPT1
GCD_MSG1:CLR A
         MOVC A,@A+DPTR
         JZ FINISH_GCD1
         LCALL DATAWRT
         LCALL DELAY
         INC DPTR
         LJMP GCD_MSG1

FINISH_GCD1:MOV A,#0C0H
            LCALL COMNWRT
            LCALL DELAY
	      
           MOV DPTR,#GCD_PROMPT2
GCD_MSG2:  CLR A
	   MOVC A,@A+DPTR
	   JZ FINISH_GCD2
	   LCALL DATAWRT
	   LCALL DELAY
	   INC DPTR
	   LJMP GCD_MSG2
FINISH_GCD2:MOV A,#'G' ; STROING G IN THE MEMORY TO INDICATE WE HAVE TO FIND GCD & LCM OF 2 NEXT MEMORY LOCATION NUMBERS
	    MOV @R0,A; ALSO STORING THESE EXTRA SYMBOLS IN RAM LOCATIONS
            INC R0
            INC R2
	    LJMP K1

RESET_PUSH: MOV A,#01H
            ;LCALL COMNWRT
            ;LCALL DELAY
            ;LJMP K1 ;PROBABLY INTERRUPT WILL BE ADDED TO MASTER RESET FUNCTION
            LJMP MAIN 
 ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;PUSH BUTTON ENDS;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
 
;;;;;;;;;FIRST CHECK IF WE HAVE TO FIND PRIME NUMBER OR GCD/LCM;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
START_CALCULATING:MOV A,30H
		  CJNE A,#'P',CHECK_GCD_MODULE
		  MOV A,31H; AS 30H LOCATION IS HOLDING 'P', SO WE WANT TO CHECK IF IT IS A PRIME NUMBER OR NOT
		  LCALL PRIME_CHECKER ; 31 H LOCATION WAS HOLDING THE NUMBER TO BE CHECKED. SO BRINGING IT TO A FOR PRIME CHECKING
		  JNC PRINT_NOT_PRIME ;CARRY FALG WAS USED AS OOUTPUT FOR THE FUNCTION
		  
		  MOV A,#01H ;CLEARING THE SCREEN. DISPLAYING AS PRIME NUMBER
            	  LCALL COMNWRT
            	  LCALL DELAY
            	  MOV DPTR,#YES_PRIME
YES_PRIME_MSG:    CLR A
	   	  MOVC A,@A+DPTR
	   	  JZ FINISH_PRIME_PRINTING
	   	  LCALL DATAWRT
	   	  LCALL DELAY
	   	  INC DPTR
	          SJMP YES_PRIME_MSG

PRINT_NOT_PRIME: MOV A,#01H ;CLEARING THE SCREEN. DISPLAYING AS NOT A PRIME NUMBER
		 LCALL COMNWRT
   	  	 LCALL DELAY
		 MOV DPTR,#NO_PRIME
NO_PRIME_MSG:    CLR A
		 MOVC A,@A+DPTR
	  	 JZ FINISH_PRIME_PRINTING
	   	 LCALL DATAWRT
	   	 LCALL DELAY
	   	 INC DPTR
	     	 SJMP NO_PRIME_MSG

FINISH_PRIME_PRINTING: LJMP DONE_DISPLAY		  

CHECK_GCD_MODULE: CJNE A,#'G',STANDARD_ARITHMATIC
		  MOV A, 32H ; OUR DEFINED INPUT RULE WILL STORE THE 2 NUMBERS IN 32H AND 35 H RAM LOCATIONS
		  MOV B, 35H
		  LCALL GCD_LCM_CHECKER
		  
		  MOV R0,A ;KEEPING THE GCD TEMPORARILY IN R0
		  MOV R1,B ;KEEPING THE LCM TEMPORARILY IN R1
		  
		  MOV A,#01H ;CLEARING THE SCREEN. DISPLAYING LCM AND GCD
            	  LCALL COMNWRT
            	  LCALL DELAY
   		 
   		  MOV DPTR,#GCD_ANS
GCD_ANS_PRINTING: CLR A
	   	  MOVC A,@A+DPTR
	   	  JZ FINISH_GCD_PRINTING_PROMPT
	   	  LCALL DATAWRT
	   	  LCALL DELAY
	   	  INC DPTR
	          SJMP GCD_ANS_PRINTING

FINISH_GCD_PRINTING_PROMPT:MOV A,R0
			   LCALL HEX2DEC
		            ;CODES FOR DISPLAY WHERE MSB=R4 LSB=R6
			   MOV A,R4
			   ADD A,#30H
			   LCALL DATAWRT
			   LCALL DELAY
		
	 		  MOV A,R5
			  ADD A,#30H
			  LCALL DATAWRT
			  LCALL DELAY
		
			  MOV A,R6
			  ADD A,#30H
			  LCALL DATAWRT
			  LCALL DELAY
		
		          MOV A,#0C0H ;START PRINTING LCM IN NEXT LINE
			  LCALL COMNWRT
			  LCALL DELAY
			  
			  MOV DPTR,#LCM_ANS
LCM_ANS_PRINTING: 	  CLR A
	   	  	  MOVC A,@A+DPTR
	   	  	  JZ FINISH_LCM_PRINTING_PROMPT
	   	 	  LCALL DATAWRT
	   	  	  LCALL DELAY
	   	  	  INC DPTR
	          	  SJMP LCM_ANS_PRINTING

FINISH_LCM_PRINTING_PROMPT:MOV A,R1
			   LCALL HEX2DEC
		            ;CODES FOR DISPLAY WHERE MSB=R4 LSB=R6
			   MOV A,R4
			   ADD A,#30H
			   LCALL DATAWRT
			   LCALL DELAY
		
	 		  MOV A,R5
			  ADD A,#30H
			  LCALL DATAWRT
			  LCALL DELAY
		
			  MOV A,R6
			  ADD A,#30H
			  LCALL DATAWRT
			  LCALL DELAY
			  LJMP DONE_DISPLAY ;DONE DISPLAYING GCD AND LCM


;;;;;;;DONE PRIME OR GCD/LCM OPERATION;;;;;;;;;;;;;;;;;;;;;;;;;

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;START CALCULATING RESULTS;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
STANDARD_ARITHMATIC: MOV R0,#30H ;STARTING MEMORY OF ALREADY STORED ITEMS
		     MOV R1,#50H ;STARTING MEMORY OF POST FIX EXPRESSION
		     MOV SP,#70H
		     MOV R4,#00H ; COUNTER FOR POST FIX EXPRESSION ELEMENTS 


CHECK_NEXT_INFIX: MOV A,@R0
		  CJNE A,#'(',CHECK_CLOSING_BRACKET
    	          PUSH 0E0H
	          INC R0
		  LJMP NEXT_INFIX_CONDITION

CHECK_CLOSING_BRACKET: CJNE A,#')',CHECK_ADDITION_CONDITION
popTILL_FIRST_BRACKET: POP 0E0H
	               CJNE A,#'(',STORE_POPPED_SYMBOL
		       INC R0 ; IF ( FOUND THAN WE WILL DISCARD IT AND START PARSING NEXT INFIX ITEM
		       LJMP NEXT_INFIX_CONDITION

STORE_POPPED_SYMBOL: MOV @R1,A ;SYMBOLS EXCEPT BRACKETS ARE GETTING STORED
	    	     INC R1
      		     INC R4
  		     SJMP popTILL_FIRST_BRACKET

CHECK_ADDITION_CONDITION:       CJNE A,#'+',CHECK_SUB_CONDITION
		                LJMP OPERATOR_CONDITION ;ALL OPERATORS WILL BE DEALT SIMILARLLY
CHECK_SUB_CONDITION:	        CJNE A,#'-',CHECK_MULTIPLICATION_CONDITION
		                LJMP OPERATOR_CONDITION; ALL OPERATORS ARE GOING IN SAME LABEL
CHECK_MULTIPLICATION_CONDITION: CJNE A,#'*',CHECK_DIVISION_CONDITION
		                LJMP OPERATOR_CONDITION
CHECK_DIVISION_CONDITION:       CJNE A,#'/',CHECK_POW_CONDITION
			        LJMP OPERATOR_CONDITION
CHECK_POW_CONDITION:	        CJNE A,#'^',DEFAULT_CONDITION
		                LJMP OPERATOR_CONDITION

OPERATOR_CONDITION: 	        MOV B,A ; [KEEPING FETCHED ITEM IN B TO PRESERVE]
WHILE_OPERATOR:   		MOV A,SP ; INITIALTING A FOR LOOP FOR OPERATOR PRECEDENCE COMPARSION
				CJNE A,#70H,CHECK_AND_CONDITION_FOR_WHILE; CHECKING IF WE REACHED BOTTOM OF STACK
				LJMP BREAK_WHILE_OPERATOR
CHECK_AND_CONDITION_FOR_WHILE:	MOV A,B ; RESTORING OLD STORED ITEM
				LCALL PRECEDENCE
				MOV A,R5
				MOV R6,A;KEEPING THE PRECEDENCE VALUE OF CURRENT ITEM IN R6
				MOV A,SP; TRYING TO GET THE TOP MOST ELEMENT OF STACK
				;DEC A
				SETB PSW.3
				CLR PSW.4 ;USING REGISTER BANK 1 FOR POINTER OPERATION
				MOV R0,A;ADDRESS OF TOP MOST ELEMENT IN STACK
				MOV A,@R0
				CLR PSW.3 ; GOING BACK TO REGISTER BANK 0
				LCALL PRECEDENCE;GETTIG PRECEDENCE OF TOP STACK ELEMENT
				MOV A,R5
				MOV R7,A; STORING PRECEDENCE OF TOP STACK ELEMENT IN R7

				MOV A,R7 ; PREPARING FOR COMPARISON
				CLR C
				SUBB A,R6 ; CARRY WILL BE 1 IF CURRENT OPERATOR HAS HIGHER PRIORITY THAN STACK
				JC BREAK_WHILE_OPERATOR;BREAKING FROM THE WHILE LOOP
				POP 0E0H ; IF LAST STACK ELEMENT HAD HIGHER PRECEDENCE
				MOV @R1,A ; SENDING TO THE POST FIX ARRAY
				INC R1
				INC R4
				LJMP WHILE_OPERATOR ; CONTINUING THE WHILE OPERATION

BREAK_WHILE_OPERATOR: 		MOV A,B ;BRINGING CURRENT ELEMENT IF IT HAD HIGHER PRIORITY THAN STACK ELEMS
				PUSH 0E0H
				INC R0
				LJMP NEXT_INFIX_CONDITION
DEFAULT_CONDITION: 		MOV @R1,A ;IT WAS A OPERAND. SO NEED TO PROCESS
				INC R1
				INC R4
				INC R0

NEXT_INFIX_CONDITION:           DJNZ R2,CHECK_NEXT_INFIX
				SJMP CHECK_LEFTOVERS

CHECK_LEFTOVERS: 		MOV A,SP ; NOW ANY REMAINIG ELEMENTS IN STACK WILL DIRECTLY BE PUT INTO POST FIX ARRAY
				CJNE A,#70H,EMPTY_STACK ;WILL START EMPTYING STACK IF NOT EQUAL
				SJMP DONE_POSTFIX; IF SP IS 70 THAN NOTHING STACK AND WE ARE DONE
			
EMPTY_STACK: 		POP 0E0H
			MOV @R1,A
			INC R1
			INC R4
			LJMP CHECK_LEFTOVERS

DONE_POSTFIX:
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;DONE POSTFIX EXPRESSION FORMING;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;START EVALUATING POSTFIX EXPRESSION;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;

MOV R1,#50H ;STARTING LOCATION OF POSTFIX EXPRESSION
;NO. OF POSTFIX ELEMENTS ARE IN R4
POST_EVALUATION: MOV A,@R1
		 CJNE A,#'+',CHECK_SUB_MODULE ;FIRST CHECKING CONDITIONS FOR EACH OPERATORS
		 POP 0F0H ;TOP MOST STACK ELEMENT IN B
	    	 POP 0E0H; 2ND ELEMENT FROM TOP IS IN A 
		 LCALL ADD_MODULE
		 PUSH 0E0H ; PUSHING THE RESULT OF OPERATION TO THE STACK
		 INC R1; GOING FOR NEXT ELEMENT IN POSTFLIX_ARRAY
		 LJMP NEXT_POSTFLIX_CONDITION

CHECK_SUB_MODULE:CJNE A,#'-',CHECK_MUL_MODULE
		 POP 0F0H ;TOP MOST STACK ELEMENT IN B
	    	 POP 0E0H; 2ND ELEMENT FROM TOP IS IN A 
		 LCALL SUB_MODULE
		 PUSH 0E0H ; PUSHING THE RESULT OF OPERATION TO THE STACK
		 INC R1; GOING FOR NEXT ELEMENT IN POSTFLIX_ARRAY
		 LJMP NEXT_POSTFLIX_CONDITION

CHECK_MUL_MODULE:CJNE A,#'*',CHECK_DIV_MODULE
		 POP 0F0H ;TOP MOST STACK ELEMENT IN B
	    	 POP 0E0H; 2ND ELEMENT FROM TOP IS IN A 
		 LCALL MUL_MODULE
		 PUSH 0E0H ; PUSHING THE RESULT OF OPERATION TO THE STACK
		 INC R1; GOING FOR NEXT ELEMENT IN POSTFLIX_ARRAY
		 LJMP NEXT_POSTFLIX_CONDITION

CHECK_DIV_MODULE:CJNE A,#'/',CHECK_POW_MODULE
		 POP 0F0H ;TOP MOST STACK ELEMENT IN B
	    	 POP 0E0H; 2ND ELEMENT FROM TOP IS IN A 
		 LCALL DIV_MODULE
		 PUSH 0E0H ; PUSHING THE RESULT OF OPERATION TO THE STACK
		 INC R1; GOING FOR NEXT ELEMENT IN POSTFLIX_ARRAY
		 LJMP NEXT_POSTFLIX_CONDITION

CHECK_POW_MODULE:CJNE A,#'^',DEFAULT_NUMBERS
		 POP 0F0H ;TOP MOST STACK ELEMENT IN B
	    	 POP 0E0H; 2ND ELEMENT FROM TOP IS IN A 
		 LCALL POW_MODULE ;WILL EVALUATE A TO THE POWER B
		 PUSH 0E0H ; PUSHING THE RESULT OF OPERATION TO THE STACK
		 INC R1; GOING FOR NEXT ELEMENT IN POSTFLIX_ARRAY
		 LJMP NEXT_POSTFLIX_CONDITION		 

DEFAULT_NUMBERS: PUSH 0E0H ;IF NUMBER FOUND THEN GETTING PUSHED INTO STACK
		 INC R1
		 SJMP NEXT_POSTFLIX_CONDITION
NEXT_POSTFLIX_CONDITION: DJNZ R4,POST_EVALUATION 
			 POP 0E0H ; POPPING THE LAST ELEMENT FROM STACK WHICH IS OUR RESULT. CURRENTLY IN A
			 SJMP DONE_POST_EVALUATION
DONE_POST_EVALUATION: MOV R7,A; KEEPING THE RESULT IN R7 SO THAT IT DOESN'T GET LOST
		     
