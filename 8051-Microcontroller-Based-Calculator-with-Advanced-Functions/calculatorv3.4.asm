;THIS FUNCTION WILL CHECK IF NUMBER IS PRIME OR NOT. INPUT MUST BE IN A
PRIME_CHECKER:    CLR PSW.3;SELECTING REGISTER BANK 2
                  SETB PSW.4
	          ;MOV R3,#0 ; COUNTER FOR DIVIDABLE NUMBERS
   	          MOV R4,#2 ; STARTING DENOMINATOR
	     	  MOV R2,A ; STORING THE ORIGINAL NUMBER AS IT WILL BE CHANGED AFTER DIV OPERATION 

AGAIN_PRIME_CHECK:MOV A,R2
		  MOV B,R4
		  DIV AB ; REMAINDER IS IN B

		  INC R4; GOING TO THE NEXT DENOMINATOR

		  MOV A,R2;MOVING THE ORIGINAL NUMBER IN A FOR COMPARISON USING SUB
		  CLR C
		  SUBB A,R4
		  JZ PRIME ;F4 IS NOW EQUALS TO THE NUMBER AND STILL NOTHING GOT DIVIDED. SO A PRIME NUMBER

		  MOV A,B ; COMPARING THE REMAINDER WITH 0
		  CJNE A,#00H,AGAIN_PRIME_CHECK ;ADND IF EQUALS TO 0 THEN NOT PRIME
		  CLR C ; SETTING LOW THE FLAG FOR NOT PRIME ,AS IT GOT DIVIDED
  		  SJMP EXIT_PRIME_CHECKER
 
		 PRIME:SETB C ; SETTING HIGH THE FLAG FOR PRIME 

EXIT_PRIME_CHECKER:CLR PSW.4 ;GOING BACK TO DEFAULT REGISTER BANK 0
		   CLR PSW.3 
		   RET

;THIS FUNCTION FINDS GCD AND LCM OF 2 NUMBERS STORED IN A AND B
GCD_LCM_CHECKER:CLR PSW.3;SELECTING REGISTER BANK 2
		SETB PSW.4
		MOV R6,A; TEMPORARY STORING
		MOV R7,B

		CLR C ;CHECKING IF A IS GREATER THAN B OR NOT. IF NOT THEN SWAPPING A & B
		SUBB A,B
		JNC OKAY_FOR_GCD
		PUSH 16H ;SWAPING A & B
		PUSH 17H
		POP 16H
		POP 17H

OKAY_FOR_GCD:      MOV A,R6;BRINGING THE ORIGINAL NUMBERS 
		   MOV B,R7
		   MOV R5,A;INITIALIZING A FOR FIRST ITERATION
		   ;MOV A,R5 ; BRINGING THE SMALL NUMBER IN A FROM PREVIOUS ITERATION

NEXT_LOOP_GCD:     MOV R4,B ; PRESERVING THE SMALL NUMBER BEFORE NEXT ITERATION STARTS
 		   DIV AB ;REMIANDER IS IN B
 		   MOV A,B ; BRINIGNG THE REMAINDER IN A
 		   CJNE A,#00,NEXT_ITER_FOR_GCD
 		   SJMP DONE_FINDING_GCD
 
NEXT_ITER_FOR_GCD: MOV A,R4 ; RESTORING THE SAVED SMALL NUMBER FROM PREVIOUS ITERATION
		   SJMP NEXT_LOOP_GCD ; REMAINDER IS STILL IN B WHICH WILL WORK AS SMALL NUMBER FOR NEXT ITERATION

DONE_FINDING_GCD:  MOV A,R4; SMALL NUMBER FROM LAST ITERATION IS THE GCD
 		   MOV R2,A ; STORING THE GCD IN R2 OF REGISTER BANK 2

;FINDING LCM:
		MOV A,R6;RESTORING ORIGINAL NUMBERS FROM STORED REGISTERS
		MOV B,R7
		MUL AB ;ASSUMING THE RESULT IS LESS THAN 255 AND THE LOWER BYTE IS IN A
		MOV B,R2; FETCHING THE CALCULATED GCD
		DIV AB ;LCM IS IN A
		MOV B,A ; STROING THE LCM IN B

		MOV A,R2 ; STROING THE GCD IN A

		CLR PSW.3; AGAIN GOING BACK TO DEFAULT REGISTER BANK 0
		CLR PSW.4
		RET

;FUNCTION FOR CONVERTING HEX TO DECIMAL
HEX2DEC: MOV B,#0AH ;ASSUMING HEX NUMBER IS IN A
	 DIV AB
	 MOV R6,B ;LSB IS IN R6
	 MOV B,#0AH
	 DIV AB
	 MOV R5,B
	 MOV R4,A ; MSB IS IN R4
	 RET 
 
